/**
 * Generates electron/src/build-mode.ts before the Electron main process is
 * compiled by tsc.
 *
 * Single source of truth for the build mode is the Angular environment file:
 *   src/environments/_environment.prod.ts   ->   mode: 'prod' | 'dev' | 'stg'
 *
 * You can override it for a single build with the APP_MODE env var, e.g.
 *   APP_MODE=stg npm run electron:make-not-publish
 *
 * Auto-update is only baked-in as ENABLED for production builds. In `stg` and
 * `dev` builds AUTO_UPDATE_ENABLED is false, so the updater never runs.
 */
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const VALID_MODES = ['prod', 'dev', 'stg'];

// electron/scripts -> repo root -> src/environments/_environment.prod.ts
const ENV_FILE = path.resolve(
  __dirname,
  '../../src/environments/_environment.prod.ts'
);
const OUT_FILE = path.resolve(__dirname, '../src/build-mode.ts');

function detectMode() {
  // 1) Explicit override wins (useful for CI / one-off builds).
  const override = (process.env.APP_MODE || '').trim();
  if (override) {
    if (VALID_MODES.includes(override)) return override;
    console.warn(
      `[build-mode] APP_MODE="${override}" is not one of ${VALID_MODES.join(
        ', '
      )} — ignoring.`
    );
  }

  // 2) Read `mode` from the Angular environment file.
  try {
    const src = fs.readFileSync(ENV_FILE, 'utf8');
    const match = src.match(/mode:\s*['"`](prod|dev|stg)['"`]/);
    if (match) return match[1];
    console.warn(`[build-mode] no \`mode\` field found in ${ENV_FILE}.`);
  } catch (err) {
    console.warn(
      `[build-mode] could not read ${ENV_FILE}: ${err.message}`
    );
  }

  // 3) Safe default: behave like a production build (update enabled).
  return 'prod';
}

/**
 * Short commit the build came from, reported to the backend as
 * `app_build_number`. The repo has no build counter — package.json and
 * electron/package.json both just repeat the app version — so the commit is the
 * only value that actually distinguishes two builds of the same version.
 *
 * 1) GIGA_METER_BUILD_NUMBER wins, for a CI pipeline that has its own build id.
 * 2) Otherwise the short git hash, which covers local and CI builds made from a
 *    checkout.
 * 3) Otherwise null, and the app falls back to the app version at runtime.
 */
function detectBuildCommit() {
  const override = (process.env.GIGA_METER_BUILD_NUMBER || '').trim();
  if (override) return override;

  try {
    return execFileSync('git', ['rev-parse', '--short', 'HEAD'], {
      cwd: __dirname,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch (_) {
    // Not a git checkout (e.g. building from an exported tarball).
    return null;
  }
}

/**
 * Versions of the speed-test SDKs that ship in this build, reported as
 * `sdk_version` on the measurement. Read from the root package.json so the value
 * cannot drift from the dependency that actually ran; the caret is stripped
 * because a row should record a version, not a range.
 */
function detectSdkVersions() {
  const PKG_FILE = path.resolve(__dirname, '../../package.json');
  const clean = (range) =>
    typeof range === 'string' ? range.replace(/^[\^~>=<\s]+/, '') : null;

  try {
    const deps = JSON.parse(fs.readFileSync(PKG_FILE, 'utf8')).dependencies || {};
    return {
      mlab: clean(deps['@m-lab/ndt7']),
      cloudflare: clean(deps['@cloudflare/speedtest']),
    };
  } catch (err) {
    console.warn(`[build-mode] could not read ${PKG_FILE}: ${err.message}`);
    return { mlab: null, cloudflare: null };
  }
}

const mode = detectMode();
const autoUpdateEnabled = mode === 'prod';
const buildCommit = detectBuildCommit();
const sdkVersions = detectSdkVersions();

const content = `// AUTO-GENERATED by electron/scripts/generate-build-mode.js — do not edit by hand.
// Derived from src/environments/_environment.prod.ts (\`mode\`) or the APP_MODE env var.
export const BUILD_MODE: 'prod' | 'dev' | 'stg' = '${mode}';

// Auto-update is only active in production builds. stg/dev builds ship without it.
export const AUTO_UPDATE_ENABLED = ${autoUpdateEnabled};

// Short commit this build came from, or null when built outside a git checkout.
// Uploaded as \`app_build_number\`; the app falls back to the app version when null.
export const BUILD_COMMIT: string | null = ${
  buildCommit ? `'${buildCommit}'` : 'null'
};

// Speed-test SDK versions bundled in this build, reported as \`sdk_version\`.
export const SDK_VERSIONS: { mlab: string | null; cloudflare: string | null } = {
  mlab: ${sdkVersions.mlab ? `'${sdkVersions.mlab}'` : 'null'},
  cloudflare: ${sdkVersions.cloudflare ? `'${sdkVersions.cloudflare}'` : 'null'},
};
`;

// Only write when the content actually changes. The live-runner watches
// ./src/**/* with chokidar, so an unconditional write would retrigger a reload
// loop on every rebuild.
let current = null;
try {
  current = fs.readFileSync(OUT_FILE, 'utf8');
} catch (_) {
  /* file does not exist yet */
}

if (current !== content) {
  fs.writeFileSync(OUT_FILE, content);
}

console.log(
  `[build-mode] mode="${mode}" -> AUTO_UPDATE_ENABLED=${autoUpdateEnabled}, ` +
    `BUILD_COMMIT=${buildCommit ?? "null"} (${OUT_FILE})`
);
