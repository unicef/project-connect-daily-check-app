/**
 * Generates electron/src/build-mode.ts before the Electron main process is
 * compiled by tsc.
 *
 * Single source of truth for the build mode is the Angular environment file:
 *   src/environments/_environment.prod.ts   ->   mode: 'prod' | 'dev' | 'stg'
 *
 * You can override it for a single build with the APP_MODE env var, e.g.
 *   APP_MODE=stg npm run electron:make-not-publish
 *
 * Auto-update is only baked-in as ENABLED for production builds. In `stg` and
 * `dev` builds AUTO_UPDATE_ENABLED is false, so the updater never runs.
 */
const fs = require('fs');
const path = require('path');

const VALID_MODES = ['prod', 'dev', 'stg'];

// electron/scripts -> repo root -> src/environments/_environment.prod.ts
const ENV_FILE = path.resolve(
  __dirname,
  '../../src/environments/_environment.prod.ts'
);
const OUT_FILE = path.resolve(__dirname, '../src/build-mode.ts');

function detectMode() {
  // 1) Explicit override wins (useful for CI / one-off builds).
  const override = (process.env.APP_MODE || '').trim();
  if (override) {
    if (VALID_MODES.includes(override)) return override;
    console.warn(
      `[build-mode] APP_MODE="${override}" is not one of ${VALID_MODES.join(
        ', '
      )} — ignoring.`
    );
  }

  // 2) Read `mode` from the Angular environment file.
  try {
    const src = fs.readFileSync(ENV_FILE, 'utf8');
    const match = src.match(/mode:\s*['"`](prod|dev|stg)['"`]/);
    if (match) return match[1];
    console.warn(`[build-mode] no \`mode\` field found in ${ENV_FILE}.`);
  } catch (err) {
    console.warn(
      `[build-mode] could not read ${ENV_FILE}: ${err.message}`
    );
  }

  // 3) Safe default: behave like a production build (update enabled).
  return 'prod';
}

const mode = detectMode();
const autoUpdateEnabled = mode === 'prod';

const content = `// AUTO-GENERATED by electron/scripts/generate-build-mode.js — do not edit by hand.
// Derived from src/environments/_environment.prod.ts (\`mode\`) or the APP_MODE env var.
export const BUILD_MODE: 'prod' | 'dev' | 'stg' = '${mode}';

// Auto-update is only active in production builds. stg/dev builds ship without it.
export const AUTO_UPDATE_ENABLED = ${autoUpdateEnabled};
`;

// Only write when the content actually changes. The live-runner watches
// ./src/**/* with chokidar, so an unconditional write would retrigger a reload
// loop on every rebuild.
let current = null;
try {
  current = fs.readFileSync(OUT_FILE, 'utf8');
} catch (_) {
  /* file does not exist yet */
}

if (current !== content) {
  fs.writeFileSync(OUT_FILE, content);
}

console.log(
  `[build-mode] mode="${mode}" -> AUTO_UPDATE_ENABLED=${autoUpdateEnabled} (${OUT_FILE})`
);
